// dotenvgen.js — generate .env and .env.example from a schema.
// Copyright (c) 2026 0xnothings
// @tool dotenvgen
// @desc Produce .env/.env.example/.env.docker from a single schema file with secret generation and validation
// @usage node tools/dotenvgen.js schema.json --out .env --gen-secrets
// @tags devops,config,generator
import { writeFileSync, readFileSync, existsSync, chmodSync } from 'node:fs';
import crypto from 'node:crypto';
import { args, get, flag, die, table } from '../_lib.js';

const o = args(process.argv.slice(2));
if (o.f.help) {
  console.log(`dotenvgen — schema driven .env generator

  node tools/dotenvgen.js <schema.json> [options]

  schema format:
  {
    "APP_NAME": "myapp",
    "JWT_SECRET": { "secret": true, "bytes": 48, "example": "generate-a-long-secret" },
    "DATABASE_URL": { "required": true, "example": "postgres://user:pass@localhost:5432/db" },
    "PORT": { "default": 3000, "type": "int" },
    "DEBUG": { "default": false, "type": "bool" }
  }

  --out <file>      write .env here (default: stdout)
  --example <file>  also write a template (default: .env.example when --out is used)
  --docker          also write a docker-compose env_file block
  --gen-secrets     generate values for entries flagged secret:true
  --force           overwrite an existing --out file
  --json            machine-readable summary
  -h, --help        this text`);
  process.exit(0);
}

const schemaFile = o._[0];
if (!schemaFile) die('usage: node tools/dotenvgen.js schema.json --out .env --gen-secrets');
if (!existsSync(schemaFile)) die(`${schemaFile} not found`);
let schema;
try { schema = JSON.parse(readFileSync(schemaFile, 'utf8')); } catch (e) { die('invalid schema JSON: ' + e.message); }

const rows = [];
const real = [], example = [];
for (const [key, rawSpec] of Object.entries(schema)) {
  const spec = typeof rawSpec === 'object' && rawSpec !== null ? rawSpec : { default: rawSpec };
  const type = spec.type || (typeof spec.default === 'boolean' ? 'bool' : Number.isInteger(spec.default) ? 'int' : 'string');
  let value, exValue;
  if (spec.secret && flag(o, 'gen-secrets')) {
    const bytes = spec.bytes || 32;
    value = spec.encoding === 'hex' ? crypto.randomBytes(bytes).toString('hex') : crypto.randomBytes(bytes).toString('base64url');
  } else if (spec.default !== undefined) {
    value = String(spec.default);
  } else if (flag(o, 'gen-secrets') && spec.example === undefined) {
    value = '';
  } else {
    value = '';
  }
  exValue = spec.example !== undefined ? String(spec.example) : (spec.default !== undefined ? String(spec.default) : `<${type}>`);
  if (spec.required && !value) rows.push({ key, status: 'REQUIRED EMPTY', type });
  else rows.push({ key, status: value ? 'set' : 'empty', type });
  real.push(`${key}=${/[\s#"']/.test(value) ? JSON.stringify(value) : value}`);
  example.push(`# ${key}${spec.required ? ' (required)' : ''}${spec.secret ? ' (secret)' : ''}\n${key}=${exValue}`);
}

const envText = `# generated by dotenvgen (0xnothings) ${new Date().toISOString()}\n` + real.join('\n') + '\n';
const exampleText = `# ${get(o, 'title', 'environment template')} — commit this file, never the real .env\n\n` + example.join('\n\n') + '\n';

if (o.f.out) {
  const out = String(get(o, 'out'));
  if (existsSync(out) && !flag(o, 'force')) die(`${out} exists — pass --force to overwrite`);
  writeFileSync(out, envText, 'utf8');
  try { chmodSync(out, 0o600); } catch {}
  const exFile = o.f.example ? String(get(o, 'example')) : '.env.example';
  writeFileSync(exFile, exampleText, 'utf8');
  console.log(`wrote ${out} (chmod 600) and ${exFile}`);
} else {
  process.stdout.write(envText);
  if (!flag(o, 'json')) process.stderr.write('\n--- .env.example ---\n' + exampleText);
}

if (flag(o, 'docker')) {
  writeFileSync('docker-compose.env.yml', `services:\n  app:\n    env_file:\n      - .env\n`, 'utf8');
  console.log('wrote docker-compose.env.yml');
}
if (flag(o, 'json')) console.log(JSON.stringify({ schema: schemaFile, keys: rows }, null, 2));
else console.error('\n' + table(rows));
